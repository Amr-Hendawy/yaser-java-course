
public class Escape {
    public static void main(String[] args) {
        System.out.print("Hello \"Yaser\" ");
        System.out.print("Hello 'Java'");
        System.out.print("Hello Java");
        System.out.print("Hello \\ Java");
        System.out.print("\n ============ \n");
        System.out.print("Hello \t\t\tJava");
        System.out.println("Hello \\ Java");
        System.out.print("Hello");
    }
}


